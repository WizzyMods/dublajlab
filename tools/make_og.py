def clamp(v, lo=0, hi=255):
    return max(lo, min(hi, int(v)))


def render():
    px = bytearray(W * H * 3)

    # arka plan: dikey gradyan + iki yumuşak ışık
    for y in range(H):
        t = y / (H - 1)
        base = (8 + 6 * t, 7 + 5 * t, 15 + 9 * t)
        for x in range(W):
            r, g, b = base
            d1 = math.hypot((x - 120) / 900.0, (y + 90) / 520.0)
            d2 = math.hypot((x - 1060) / 760.0, (y + 40) / 460.0)
            g1 = max(0.0, 1.0 - d1) ** 2
            g2 = max(0.0, 1.0 - d2) ** 2
            r += 167 * 0.30 * g1 + 34 * 0.12 * g2
            g += 139 * 0.30 * g1 + 211 * 0.12 * g2
            b += 250 * 0.30 * g1 + 238 * 0.12 * g2
            i = (y * W + x) * 3
            px[i] = clamp(r)
            px[i + 1] = clamp(g)
            px[i + 2] = clamp(b)

    def blend(x, y, color, alpha=1.0):
        if x < 0 or y < 0 or x >= W or y >= H:
            return
        i = (y * W + x) * 3
        px[i] = clamp(px[i] * (1 - alpha) + color[0] * alpha)
        px[i + 1] = clamp(px[i + 1] * (1 - alpha) + color[1] * alpha)
        px[i + 2] = clamp(px[i + 2] * (1 - alpha) + color[2] * alpha)

    def text(s, x0, y0, scale, color, alpha=1.0):
        x = x0
        for ch in s:
            glyph = FONT.get(ch, FONT[" "])
            for gy, row in enumerate(glyph):
                for gx, bit in enumerate(row):
                    if bit != "1":
                        continue
                    for sy in range(scale):
                        for sx in range(scale):
                            blend(x + gx * scale + sx, y0 + gy * scale + sy, color, alpha)
            x += 6 * scale

    def text_width(s, scale):
        return len(s) * 6 * scale

    # çerçeve ve aksan çizgileri
    for x in range(80, 1120):
        for y in range(124, 127):
            blend(x, y, (167, 139, 250), 0.8)
    for x in range(80, 260):
        for y in range(500, 505):
            blend(x, y, (34, 211, 238), 0.9)

    title = "DUBLAJLAB"
    t_scale = 15
    text(title, 78, 158, t_scale, (240, 236, 255))

    price = "$6.99"
    p_scale = 7
    text(price, 1120 - text_width(price, p_scale), 196, p_scale, (200, 255, 120))

    sub = "TURKCE DUBLAJ + ALTYAZI"
    s_scale = 6
    text(sub, 84, 380, s_scale, (167, 139, 250))

    url = "DUBLAJLAB.PAGES.DEV"
    u_scale = 4
    text(url, 84, 540, u_scale, (150, 146, 172), 0.95)

    return px


def write_png(path, pixels):
    raw = bytearray()
    for y in range(H):
        raw.append(0)
        raw.extend(pixels[y * W * 3:(y + 1) * W * 3])

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
           + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))
    Path(path).write_bytes(png)
    print(f"{path} yazıldı ({len(png)} bayt)")


